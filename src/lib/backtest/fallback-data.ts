/**
 * 在節點間線性插值，生成每個交易日的資料
 * 跳過週末（週六、週日）
 */
function interpolateWaypoints(waypoints: Waypoint[]): DailyPrice[] {
  if (waypoints.length === 0) return [];
  
  const result: DailyPrice[] = [];
  
  for (let i = 0; i < waypoints.length - 1; i++) {
    const wp1 = waypoints[i];
    const wp2 = waypoints[i + 1];
    
    const d1 = new Date(wp1.date);
    const d2 = new Date(wp2.date);
    const daysDiff = Math.round((d2.getTime() - d1.getTime()) / (86400000));
    
    // Add the first waypoint
    if (i === 0) {
      result.push({
        date: wp1.date,
        open: Math.round(wp1.close + (Math.random() - 0.5) * 60),
        high: wp1.high || Math.round(wp1.close * 1.005),
        low: wp1.low || Math.round(wp1.close * 0.995),
        close: wp1.close,
        volume: Math.round(200000000000 + Math.random() * 100000000000),
      });
    }
    
    // Interpolate trading days between wp1 and wp2
    if (daysDiff > 1) {
      const tradingDays: string[] = [];
      for (let d = 1; d < daysDiff; d++) {
        const date = new Date(d1.getTime() + d * 86400000);
        const dow = date.getDay();
        if (dow === 0 || dow === 6) continue; // skip weekends
        const dateStr = date.toISOString().split('T')[0];
        tradingDays.push(dateStr);
      }
      
      for (let j = 0; j < tradingDays.length; j++) {
        const t = (j + 1) / (tradingDays.length + 1);
        const close = Math.round(wp1.close + (wp2.close - wp1.close) * t);
        const noise = Math.round((Math.random() - 0.5) * Math.abs(wp2.close - wp1.close) * 0.15);
        const adjClose = close + noise;
        
        result.push({
          date: tradingDays[j],
          open: Math.round(adjClose + (Math.random() - 0.5) * 60),
          high: Math.round(adjClose * (1 + Math.random() * 0.008)),
          low: Math.round(adjClose * (1 - Math.random() * 0.008)),
          close: adjClose,
          volume: Math.round(200000000000 + Math.random() * 100000000000),
        });
      }
    }
    
    // Add wp2
    result.push({
      date: wp2.date,
      open: Math.round(wp2.close + (Math.random() - 0.5) * 60),
      high: wp2.high || Math.round(wp2.close * 1.005),
      low: wp2.low || Math.round(wp2.close * 0.995),
      close: wp2.close,
      volume: Math.round(200000000000 + Math.random() * 100000000000),
    });
  }
  
  return result;
}

/**
 * 取得完整歷史資料
 * - 2020/01 ~ 2024/06: 由 KEY_WAYPOINTS 插值產生
 * - 2024/07 ~ 2026/02: 使用每日詳細 DAILY_WAYPOINTS
 */
export function getFallbackData(): DailyPrice[] {
  // 對稀疏節點做插值
  const interpolated = interpolateWaypoints(KEY_WAYPOINTS);
  
  // 每日資料直接轉換
  const daily: DailyPrice[] = DAILY_WAYPOINTS.map(wp => ({
    date: wp.date,
    open: Math.round(wp.close + (Math.random() - 0.5) * 100),
    high: wp.high || Math.round(wp.close * 1.005),
    low: wp.low || Math.round(wp.close * 0.995),
    close: wp.close,
    volume: Math.round(200000000000 + Math.random() * 100000000000),
  }));
  
  // 合併並依日期排序
  const all = [...interpolated, ...daily];
  all.sort((a, b) => a.date.localeCompare(b.date));
  
  // 去重（同一日期取後者，即 DAILY_WAYPOINTS 優先）
  const seen = new Set<string>();
  const result: DailyPrice[] = [];
  for (let i = all.length - 1; i >= 0; i--) {
    if (!seen.has(all[i].date)) {
      seen.add(all[i].date);
      result.push(all[i]);
    }
  }
  result.reverse();
  
  return result;
}
